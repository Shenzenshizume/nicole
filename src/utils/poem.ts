export const poemLines = [
  "Sa rosas na himig ng umagang kay lambing,",
  "Nicole Missiona, ikaw ang munting ningning;",
  "Sa bawat ngiti, may kislap na pag-asa,",
  "Parang bituing sayaw sa kalangitang masaya.",
  "Sa bawat usap natin, dahan-dahang nabubuo,",
  "Mga salitang simple, pero puso ko'y natutunaw;",
  "Kung sa dulo ng landas may tamang oras at tala,",
  "Sana ikaw na—sa akin, sa araw at sa pangarap na tala.",
];

export function getPoemText() {
  return poemLines.join("\n");
}

